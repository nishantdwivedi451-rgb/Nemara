#!/usr/bin/env node
/** Outlines the NEMARA wordmark + tagline from Cinzel (OFL) into lib/brand/logo-paths.ts, so the logo never depends on a font loading. */
import fs from "node:fs";
import path from "node:path";
import opentype from "opentype.js";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const font = (w) => opentype.parse(fs.readFileSync(path.join(ROOT, `node_modules/@fontsource/cinzel/files/cinzel-latin-${w}-normal.woff`)).buffer);

const n = (v) => +v.toFixed(2);
const toD = (cmds) => cmds.map((c) => c.type === "Z" ? "Z" : c.type === "Q" ? `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}` : c.type === "C" ? `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}` : `${c.type}${n(c.x)} ${n(c.y)}`).join("");

/** Lays out text with tracking (em), scaled so cap height = `cap` units, baseline at y = cap. */
function outline(f, text, cap, tracking) {
  const capH = f.tables.os2.sCapHeight || 700;
  const size = (cap / capH) * f.unitsPerEm;
  let x = 0, d = "";
  for (const ch of text) {
    const g = f.charToGlyph(ch);
    if (ch !== " ") d += toD(g.getPath(x, cap, size).commands);
    x += (g.advanceWidth / f.unitsPerEm) * size + tracking * size;
  }
  const width = x - tracking * size;
  return { d, width: +width.toFixed(2), height: cap };
}

const word = outline(font(500), "NEMARA", 100, 0.3);
const tag = outline(font(500), "YOUR JEWELLERY WARDROBE", 100, 0.32);
const out = `// Generated by scripts/brand/build-logo.mjs from Cinzel (SIL OFL). Do not edit by hand.
export const WORDMARK = ${JSON.stringify(word)} as const;
export const TAGLINE = ${JSON.stringify(tag)} as const;
`;
fs.writeFileSync(path.join(ROOT, "lib/brand/logo-paths.ts"), out);
console.log("wordmark", word.width, "x", word.height, "· tagline", tag.width);
